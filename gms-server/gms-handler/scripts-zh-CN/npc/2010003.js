function start() {
    cm.getPlayer().setCS(true);
    status = -1;
    action(1, 0, 0);
}

function action(mode, type, selection) {
    if (mode == 1) {
        status++;
    } else {
        if (status >= 0) {
            cm.sendNext("如果你改变主意想制作或升级手套，随时可以再来找我。");
        }
        cm.dispose();
        return;
    }

    // -------------------------------------------------------------------------
    // 第一步：主菜单选择职业
    // -------------------------------------------------------------------------
    if (status == 0) {
        var selStr = "你好！我是天空之城最好的手套打造师。你需要我帮制作或升级手套吗？#b";
        var options = [
            "制作或升级 战士手套",
            "制作或升级 弓箭手手套",
            "制作或升级 魔法师手套",
            "制作或升级 盗贼手套"
        ];

        for (var i = 0; i < options.length; i++) {
            selStr += "\r\n#L" + i + "# " + options[i] + "#l";
        }
        cm.sendSimple(selStr);

    // -------------------------------------------------------------------------
    // 第二步：根据选定的职业，展示二级装备制作/升级列表
    // -------------------------------------------------------------------------
    } else if (status == 1) {
        selectedType = selection;
        var config = craftData[selectedType];

        if (!config) {
            cm.dispose();
            return;
        }

        var selStr = config.text;
        for (var i = 0; i < config.items.length; i++) {
            selStr += "\r\n#L" + i + "# #t" + config.items[i] + "##k (等级限制：" + config.reqLevels[i] + "，" + config.jobs[i] + ")#l#b";
        }
        cm.sendSimple(selStr);

    // -------------------------------------------------------------------------
    // 第三步：确认制作目标，展示所需的材料与金币
    // -------------------------------------------------------------------------
    } else if (status == 2) {
        selectedItem = selection;
        var config = craftData[selectedType];

        item = config.items[selectedItem];
        mats = config.matSet[selectedItem];
        matQty = config.matQtySet[selectedItem];
        cost = config.costSet[selectedItem];

        var prompt = "你想让我制作 #t" + item + "# 吗？这样的话，我需要你提供一些指定的材料。制作前请确保物品栏有足够的空间！#b\r\n";

        if (mats instanceof Array) {
            for (var i = 0; i < mats.length; i++) {
                prompt += "\r\n#i" + mats[i] + "# #b#t" + mats[i] + "# " + matQty[i] + "个#k";
            }
        } else {
            prompt += "\r\n#i" + mats + "# #b#t" + mats + "# " + matQty + "个#k";
        }

        if (cost > 0) {
            prompt += "\r\n#i4031138# #b" + cost + " 金币#k";
        }

        cm.sendYesNo(prompt);

    // -------------------------------------------------------------------------
    // 第四步：扣除材料金币，发放装备成品
    // -------------------------------------------------------------------------
    } else if (status == 3) {
        var complete = true;

        if (!cm.canHold(item, 1)) {
            cm.sendOk("请先检查你的装备栏是否有足够的空位。");
            cm.dispose();
            return;
        } else if (cost > 0 && cm.getMeso() < cost) {
            cm.sendOk("恐怕你付不起我的手续费。");
            cm.dispose();
            return;
        } else {
            if (mats instanceof Array) {
                for (var i = 0; complete && i < mats.length; i++) {
                    if (!cm.haveItem(mats[i], matQty[i])) {
                        complete = false;
                    }
                }
            } else if (!cm.haveItem(mats, matQty)) {
                complete = false;
            }
        }

        if (!complete) {
            cm.sendOk("如果你想做出高品质的手套，拿替代材料来凑数可不行，真抱歉。");
        } else {
            if (mats instanceof Array) {
                for (var i = 0; i < mats.length; i++) {
                    cm.gainItem(mats[i], -matQty[i]);
                }
            } else {
                cm.gainItem(mats, -matQty);
            }

            if (cost > 0) {
                cm.gainMeso(-cost);
            }

            cm.gainItem(item, 1);
            cm.sendOk("制作好了！如果你还需要制作其他装备，随时来找我。");
        }
        cm.dispose();
    }
}