-- ============================================================
-- 任务ID 由 short 改为 int 后的历史数据修复
--
-- 旧代码：QuestV2.id / QuestStatus.questID 都是 short，数据库 queststatus.quest 是 int。
-- 自定义任务ID（100000+）在写入数据库前被 (short) 截断，落库成了负数：
--     100000 -> -31072
--     100200 -> -30872
--     100201 -> -30871
--     100202 -> -30870
--     100400 -> -30672
--
-- 截断只保留低 16 位，且负数无法唯一反推原ID（例如 -30872 可能是 100200、165736……），
-- 所以不能简单写 quest = quest + 65536，必须按“已知自定义ID区间”整体补偿 131072：
--     原ID(100000~100999) = 负数 + 131072  ->  -31072~-30073
--
-- 如果要新增其它区间的自定义ID，请先确认该区间的截断公式，再补一条同样的 UPDATE。
-- 真实任务ID（小于 32768）都是正数，不受影响。
-- ============================================================

UPDATE `queststatus`
SET `quest` = `quest` + 131072
WHERE `quest` BETWEEN -31072 AND -30073;



